const cache = new Map<string, number[]>();

/** Returns 7 row bitmasks (5 bits, bit 4 = leftmost column) for a character. */
export function glyph(ch: string): number[] {
  let c = ch;
  if (!(c in G)) c = c.toUpperCase();
  if (!(c in G)) c = '?';
  let rows = cache.get(c);
  if (!rows) {
    rows = G[c].split(' ').map((r) => parseInt(r, 2));
    cache.set(c, rows);
  }
  return rows;
}
